-- Drop existing tables if they already exist (in reverse dependency order)
DROP TABLE IF EXISTS Projects CASCADE;
DROP TABLE IF EXISTS Employees CASCADE;
DROP TABLE IF EXISTS Departments CASCADE;

-- ============================================================================
-- Table 1: Departments
-- Business Rules:
-- 1. Each department must have a unique department ID and a unique department name.
-- 2. Every department must have a department name and a creation date.
-- 11. IDs generated automatically using PostgreSQL IDENTITY.
-- 12. Suitable data types (INT, VARCHAR, DATE).
-- ============================================================================
CREATE TABLE Departments (
    dept_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dept_name VARCHAR(100) NOT NULL UNIQUE,
    creation_date DATE NOT NULL,
    dept_location VARCHAR(100) NOT NULL
);

COMMENT ON TABLE Departments IS 'Stores organizational departments';
COMMENT ON COLUMN Departments.dept_id IS 'Unique Department Identifier (Primary Key, Auto-incremented)';
COMMENT ON COLUMN Departments.dept_name IS 'Unique name of the department (Required)';
COMMENT ON COLUMN Departments.creation_date IS 'Official founding date of the department (Required)';
COMMENT ON COLUMN Departments.dept_location IS 'Physical office location/city of the department';

-- ============================================================================
-- Table 2: Employees
-- Business Rules:
-- 3. Each employee must have a unique employee ID.
-- 4. An employee may belong to one department.
-- 11. IDs generated automatically using PostgreSQL IDENTITY.
-- 12. Suitable data types (INT, VARCHAR, DATE, NUMERIC).
-- 13. Proper foreign key relationship referencing Departments(dept_id).
-- ============================================================================
CREATE TABLE Employees (
    emp_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    emp_name VARCHAR(100) NOT NULL,
    designation VARCHAR(100) NOT NULL,
    dateofbirth DATE NOT NULL,
    salary NUMERIC(10, 2) NOT NULL CHECK (salary >= 0),
    dept_id INT,
    CONSTRAINT fk_employees_department FOREIGN KEY (dept_id)
        REFERENCES Departments (dept_id)
        ON DELETE SET NULL
        ON UPDATE CASCADE
);

COMMENT ON TABLE Employees IS 'Stores organizational employee information';
COMMENT ON COLUMN Employees.emp_id IS 'Unique Employee Identifier (Primary Key, Auto-incremented)';
COMMENT ON COLUMN Employees.emp_name IS 'Full legal name of the employee (Required)';
COMMENT ON COLUMN Employees.designation IS 'Job title / position (Required)';
COMMENT ON COLUMN Employees.dateofbirth IS 'Date of birth of the employee (Required)';
COMMENT ON COLUMN Employees.salary IS 'Monthly salary in BDT, must be non-negative (Required)';
COMMENT ON COLUMN Employees.dept_id IS 'Department to which the employee belongs (Foreign Key -> Departments.dept_id)';

-- ============================================================================
-- Table 3: Projects
-- Business Rules:
-- 5. Each project must have a unique project ID.
-- 6. Every project must have a project name.
-- 7. A project must have one project manager.
-- 8. The project manager must be an employee of the organization.
-- 9. A project may have one employee working on it.
-- 10. An employee may work on multiple projects (supported via 1-to-many relationship).
-- 11. IDs generated automatically using PostgreSQL IDENTITY.
-- 12. Suitable data types (INT, VARCHAR, SMALLINT/BOOLEAN).
-- 13. Foreign key constraints referencing Employees(emp_id) for both assigned employee and project manager.
-- ============================================================================
CREATE TABLE Projects (
    project_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_name VARCHAR(150) NOT NULL,
    emp_id INT,
    project_manager INT NOT NULL,
    is_finished SMALLINT NOT NULL DEFAULT 0 CHECK (is_finished IN (0, 1)),
    CONSTRAINT fk_projects_assigned_employee FOREIGN KEY (emp_id)
        REFERENCES Employees (emp_id)
        ON DELETE SET NULL
        ON UPDATE CASCADE,
    CONSTRAINT fk_projects_manager FOREIGN KEY (project_manager)
        REFERENCES Employees (emp_id)
        ON DELETE RESTRICT
        ON UPDATE CASCADE
);

COMMENT ON TABLE Projects IS 'Stores company projects and their assignments';
COMMENT ON COLUMN Projects.project_id IS 'Unique Project Identifier (Primary Key, Auto-incremented)';
COMMENT ON COLUMN Projects.project_name IS 'Project title/name (Required)';
COMMENT ON COLUMN Projects.emp_id IS 'Employee assigned to work on the project (Foreign Key -> Employees.emp_id)';
COMMENT ON COLUMN Projects.project_manager IS 'Employee who manages this project (Foreign Key -> Employees.emp_id, Required)';
COMMENT ON COLUMN Projects.is_finished IS 'Status indicator: 1 = Completed, 0 = Running (Default: 0)';
